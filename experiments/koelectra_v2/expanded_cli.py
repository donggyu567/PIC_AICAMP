"""Explicit preflight/train/select/final-evaluate CLI. Never manufactures evidence."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import sys

from expanded_common import (ROOT, OUTPUT, REVISION, SEEDS, ARMS, GateError, checked_file,
                             compile_runtime, digest, read, require, sha, slug, write_json)
from expanded_data import load_partition, load_receipt, check_disjoint


def tokenizer(cache):
    from expanded_assets import load_tokenizer
    return load_tokenizer(cache)


def inputs(path, root=ROOT):
    require(path is not None and Path(path).is_file(), 'Missing external input bundle; no manifests will be synthesized')
    bundle = read(path)
    require(bundle.get('schema') == 'expanded-inputs/1', 'Unknown input bundle schema')
    return bundle


def partitions(bundle, root=ROOT, *, synthetic=False):
    base = load_partition(root, checked_file(root, bundle['train']), 'train')
    val = load_partition(root, checked_file(root, bundle['validation']), 'validation')
    receipt = load_receipt(root, bundle['test_receipt'])
    extra = None
    if synthetic:
        require('synthetic_train' in bundle, 'C BLOCKED: final-approved synthetic TRAIN count=0/no manifest')
        extra = load_partition(root, checked_file(root, bundle['synthetic_train']), 'synthetic_train')
        check_disjoint(base, val, extra)
    else:
        check_disjoint(base, val)
    require(receipt.verify()['split_sha256'] == base.bindings['split_sha256'], 'Receipt split mismatch')
    return base, val, extra, receipt


def candidate_preflight(kind, cache):
    """Only existing gate preflight adapters and DataLoader; no model/metrics/optimizer."""
    sys.path.insert(0, str(ROOT / 'dataset/scripts'))
    from v2_pipeline_gate import prepare_partition
    from risk_speech_ai.training_data import TrainingSample
    from risk_speech_ai.labels import to_multi_hot
    from risk_speech_ai.dataset import RiskSpeechDataset, make_training_dataloader
    from expanded_common import LABELS
    role, file = ('train', 'v2_train_expansion/train_24_mixed_review_candidate.jsonl') if kind == 'train' else (
        'validation', 'v2_validation/validation_24_generated.jsonl')
    data = [json.loads(line) for line in (ROOT / 'dataset/04. processed' / file).read_text(encoding='utf-8').splitlines()]
    prepared = prepare_partition(data, split=role, mode='preflight', sample_type=TrainingSample, to_multi_hot=to_multi_hot)
    require(prepared.training_allowed is False, 'Preflight must not grant training eligibility')
    tok = tokenizer(cache)
    loader = make_training_dataloader(RiskSpeechDataset(prepared.samples, tokenizer=tok), tokenizer=tok, batch_size=8, shuffle=False)
    count = batches = 0
    for batch in loader:
        n, width = batch['input_ids'].shape
        require(width <= 512 and all(x.device.type == 'cpu' for x in batch.values()), 'CPU/token contract failed')
        require(batch['risk_target'].shape == (n, 1) and batch['type_targets'].shape == (n, len(LABELS)), 'Target shape failed')
        count += n
        batches += 1
    return dict(mode='preflight', role=role, samples=count, batches=batches, training_authorized=False,
                optimizer_created=False, model_forward=False, threshold_selection=False, test_access=False)


def selection_from_files(index, base, val, arm='B_ratio'):
    from expanded_selection import select_epoch, freeze_b, validate_frozen_checkpoints
    from expanded_training import positive_weights
    from expanded_evaluation import validate_predictions
    from expanded_checkpoint import load_v2
    require(index.get('schema') == 'expanded-prediction-index/1', 'Unknown prediction index')
    predictions = {}
    for epoch, seed_refs in index['epochs'].items():
        predictions[int(epoch)] = {}
        for seed, spec in seed_refs.items():
            item = read(checked_file(ROOT, spec))
            validate_predictions(item, val)
            path = Path(item['checkpoint']['path']).resolve()
            require(path.is_relative_to(OUTPUT.resolve()), 'Unregistered checkpoint namespace')
            checkpoint = load_v2(path, expected_sha256=item['checkpoint']['sha256'])
            meta = checkpoint['expanded_metadata']
            require(meta['arm'] == item['arm'] == arm and meta['seed'] == int(seed) == item['seed'] and
                    meta['epoch'] == int(epoch) == item['epoch'], 'Prediction/checkpoint identity differs')
            require(meta['bindings']['train'] == base.bindings and meta['bindings']['validation'] == val.bindings,
                    'Checkpoint/input bindings differ')
            # Predictions are generated by gated inference and bound to this immutable checkpoint.
            # Re-inference in select mode below verifies the values rather than trusting an editable JSON.
            predictions[int(epoch)][int(seed)] = item
    return predictions


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=['preflight', 'train', 'select', 'final-evaluate'])
    parser.add_argument('--arm', choices=ARMS, default='A0')
    parser.add_argument('--seed', type=int, choices=SEEDS, default=42)
    parser.add_argument('--inputs', type=Path)
    parser.add_argument('--cache', type=Path, default=ROOT.parents[1] / '.venv-ai/hf-cache/hub')
    parser.add_argument('--candidate', choices=['train', 'aux-validation'])
    parser.add_argument('--run-id')
    parser.add_argument('--selection', type=Path)
    parser.add_argument('--prediction-index', type=Path)
    parser.add_argument('--evaluation-root', type=Path)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--release', type=Path)
    parser.add_argument('--checkpoint', type=Path)
    args = parser.parse_args(argv)
    try:
        require(not args.candidate or args.mode == 'preflight', 'Candidates may only enter preflight')
        if args.mode == 'preflight':
            if args.candidate:
                result = candidate_preflight(args.candidate, args.cache)
            else:
                from expanded_common import load_design
                design = load_design()
                result = dict(mode='preflight', training_authorized=False,
                              missing_manifests=[item['path'] for item in design['data']['future_required']
                                                 if not (ROOT / item['path']).is_file()])
            if args.output:
                write_json(args.output, result)
            print(json.dumps(result, ensure_ascii=False, indent=2))
            return 0
        require(args.run_id is not None, 'Explicit unique run-id required')
        slug(args.run_id)
        if args.mode == 'final-evaluate':
            return final_evaluate(args)
        bundle = inputs(args.inputs)
        base, val, synthetic, receipt = partitions(bundle, synthetic=args.mode == 'train' and args.arm in ('C_approved', 'B_step_matched'))
        tok = tokenizer(args.cache)
        if args.mode == 'train':
            from expanded_training import train
            frozen = read(args.selection) if args.selection else None
            config = compile_runtime(args.arm, args.seed, frozen=frozen)
            result = train(config, base, val, tok, run_id=args.run_id, synthetic=synthetic, receipt=receipt, cache=args.cache)
        else:
            require(args.prediction_index and args.output, 'Prediction index and new selection output required')
            from expanded_selection import select_epoch, freeze_b, save_selection, validate_frozen_checkpoints
            from expanded_training import positive_weights
            from expanded_checkpoint import model_for_inference
            from expanded_evaluation import infer_partition
            selection_arm = 'B_ratio' if args.arm == 'B_threshold' else args.arm
            require(selection_arm in ('B_ratio', 'A_epoch', 'B_sqrt5_legacy'), 'Select requires --arm B_ratio, B_threshold, A_epoch or B_sqrt5_legacy')
            predictions = selection_from_files(read(args.prediction_index), base, val, selection_arm)
            for epoch, items in predictions.items():
                for seed, item in items.items():
                    ref = item['checkpoint']
                    model, _ = model_for_inference(ref['path'], expected_sha256=ref['sha256'], tokenizer=tok)
                    actual = infer_partition(model, tok, val, seed=seed, epoch=epoch, arm=selection_arm)
                    require(actual['logits'] == item['logits'], 'Stored validation predictions differ from checkpoint inference')
                    del model
            chosen = select_epoch(predictions, val)['epoch']
            refs = {str(seed): predictions[chosen][seed]['checkpoint'] for seed in SEEDS}
            if selection_arm == 'B_ratio':
                result = freeze_b(predictions, val, positive_weights(base)['values'], base.bindings,
                                  version=args.run_id, checkpoints=refs)
                validate_frozen_checkpoints(result)
                save_selection(args.output, result)
            else:
                from expanded_common import PROTOCOL_SHA
                result = dict(schema='expanded-epoch-selection/1', arm=selection_arm, protocol_sha256=PROTOCOL_SHA,
                              source='validation', version=args.run_id, epoch=chosen, thresholds=[.5]*9,
                              checkpoint_references=refs, validation_bindings=val.bindings, train_bindings=base.bindings,
                              epoch_scores=select_epoch(predictions, val)['mean_seed_f1'])
                write_json(args.output, result)
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0
    except (GateError, FileNotFoundError, KeyError, ValueError) as error:
        print(json.dumps(dict(status='BLOCKED', mode=args.mode, reason=str(error)), ensure_ascii=False))
        return 2


def final_evaluate(args):
    from expanded_selection import validate_frozen
    from expanded_checkpoint import model_for_inference
    from expanded_evaluation import infer_partition, evaluate_logits, validate_final_plan
    require(all((args.evaluation_root, args.release, args.checkpoint, args.selection, args.output)),
            'Custodian root, human release, selected checkpoint, frozen selection and output required')
    root = args.evaluation_root.resolve()
    require(not root.is_relative_to(ROOT.resolve()), 'TEST content belongs outside the development repository')
    require(args.output.resolve().is_relative_to(root) and not args.output.exists(),
            'Final report needs a new path inside the custodian root')
    require(args.checkpoint.resolve().is_relative_to(OUTPUT.resolve()), 'Final model must be a registered v2 output')
    bundle = inputs(args.inputs, root)
    selection = read(args.selection)
    if selection.get('schema') == 'expanded-final-plan/1':
        plan = validate_final_plan(selection)
        frozen_b = plan['frozen_b']
        require(args.arm in plan['models'], 'Model not registered in final plan')
        entry = plan['models'][args.arm][str(args.seed)]
        require(Path(entry['checkpoint']['path']).resolve() == args.checkpoint.resolve() and
                entry['checkpoint']['sha256'] == sha(args.checkpoint), 'Final checkpoint differs from frozen registry')
        final_epoch, thresholds, threshold_version = entry['epoch'], entry['thresholds'], entry['threshold_version']
    else:
        validate_frozen(selection)
        require(args.arm in ('B_ratio', 'C_approved'), 'A/control arms require the separate frozen final model registry')
        frozen_b = selection
        final_epoch, thresholds, threshold_version = selection['epoch'], selection['thresholds'], selection['version']
    release = args.release.resolve()
    require(release.is_relative_to(root), 'Release must belong to custodian root')
    capability = dict(release=dict(path=release.relative_to(root).as_posix(), sha256=sha(release)),
                      receipt=bundle['test_receipt'], selection_sha256=sha(args.selection),
                      checkpoint_sha256=sha(args.checkpoint))
    tok = tokenizer(args.cache)
    model, checkpoint = model_for_inference(args.checkpoint, expected_sha256=capability['checkpoint_sha256'], tokenizer=tok)
    meta = checkpoint['expanded_metadata']
    require(meta['seed'] == args.seed and meta['arm'] == args.arm and meta['epoch'] == final_epoch, 'Final model identity differs')
    require(meta['bindings']['train'] == frozen_b['train_bindings'] and
            meta['bindings']['validation'] == frozen_b['validation_bindings'], 'Final model data differs')
    if args.arm in ('B_ratio', 'C_approved', 'B_step_matched'):
        require(meta['weights'] == frozen_b['weights'], 'Final model not bound to B weights')
    if args.arm in ('C_approved', 'B_step_matched'):
        require(meta['thresholds'] == thresholds and meta['threshold_version'] == threshold_version, 'C thresholds differ')
    partition = load_partition(root, checked_file(root, bundle['test']), 'test', mode='final-evaluate', test_capability=capability)
    require(partition.bindings['split_sha256'] == frozen_b['validation_bindings']['split_sha256'], 'Final TEST split differs')
    result = infer_partition(model, tok, partition, seed=args.seed, epoch=meta['epoch'], arm=args.arm)
    metrics = evaluate_logits(partition.rows, result['logits'], thresholds)
    write_json(args.output, dict(metrics=metrics, checkpoint_sha256=capability['checkpoint_sha256'],
                                selection_sha256=capability['selection_sha256'], receipt=bundle['test_receipt']))
    print(json.dumps(dict(status='FINAL_EVALUATION_WRITTEN', output=str(args.output))))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
