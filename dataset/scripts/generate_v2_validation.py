def write_new(path, content, *, bom=False):
    path.parent.mkdir(parents=True, exist_ok=True)
    data = content.encode("utf-8-sig" if bom else "utf-8")
    if path.exists():
        if path.read_bytes() != data:
            raise FileExistsError(f"Refusing to replace existing artifact: {path}")
        return
    with path.open("xb") as stream:
        stream.write(data)


def expected_review_rows(conversations):
    rows = []
    for c in conversations:
        design = next(d for d in DESIGNS if d["synthetic_id"] == c["synthetic_id"])
        for u in c["utterances"]:
            row = dict(zip(review.SOURCE_COLUMNS, [
                c["synthetic_id"], f"{c['synthetic_id']}-{u['utterance_id']}", str(u["utterance_id"]),
                u["speaker"], c["scenario_summary"], u["text"], str(u["is_phishing"]).lower(),
                json.dumps(u["labels"], ensure_ascii=False), u["label_rationale"], "예",
                design["human_review_focus"], *review.REVIEWERS, "미반영",
            ]))
            for name in review.REVIEWERS:
                row.update({f"검수_결과_{name}": "미승인", f"수정_의견_{name}": "", f"검수_일시_{name}": ""})
            row.update(최종_합의_결과="미승인", 합의_수정안="", 최종_합의_일시="")
            rows.append(row)
    return rows


